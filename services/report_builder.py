"""
services/report_builder.py
Security Report Builder for Cybex Recon Engine.
Generates TXT and JSON assessment reports including live scan metadata,
authorization confirmation timestamp, and OSV.dev data source attribution.
"""

import json
import uuid
from datetime import datetime, timezone


def generate_txt_report(analysis: dict) -> str:
    """
    Render *analysis* results as a formatted plain-text security report.

    Parameters
    ----------
    analysis : dict
        The analysis result generated by services/analysis.py.

    Returns
    -------
    str
        Plain-text security report content.
    """
    report_id    = analysis.get("report_id") or str(uuid.uuid4())
    generated_at = analysis.get("generated_at") or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    live_scan    = analysis.get("live_scan", False)
    auth_ts      = analysis.get("auth_confirmed_at") or "N/A"

    sep      = "=" * 72
    thin_sep = "-" * 72
    lines    = []

    # ── Title & Header ──────────────────────────────────────────────────────
    scan_type = "LIVE TCP SCAN" if live_scan else "SIMULATED SERVICE EXPOSURE"
    lines += [
        sep,
        f"  CYBEX RECON ENGINE  -  {scan_type} REPORT",
        "  Module 3: Security Analysis & Reporting",
        sep,
        "",
        f"  Report ID          : {report_id}",
        f"  Generated At       : {generated_at}",
        f"  Target             : {analysis['target']}",
        f"  Scenario           : {analysis['scenario']}",
        f"  Assessment Date    : {analysis['assessment_date']}",
        f"  Scan Type          : {'LIVE (real TCP connect scan)' if live_scan else 'SIMULATED (fixture data)'}",
        f"  Auth Confirmed At  : {auth_ts}",
        f"  Risk Score         : {analysis['risk_score']}/100  [{analysis['risk_label']}]",
    ]

    sb = analysis.get("score_breakdown", {})
    breakdown_str = (
        f"Critical: {sb.get('critical', 0)}, High: {sb.get('high', 0)}, "
        f"Medium: {sb.get('medium', 0)}, Low: {sb.get('low', 0)}"
    )
    lines.append(f"  Risk Breakdown     : {breakdown_str}")
    lines.append("")

    # ── Authorization & Disclaimer ───────────────────────────────────────────
    lines += [
        sep,
        "  AUTHORIZATION & DISCLAIMER",
        sep,
        "",
    ]
    if live_scan:
        lines += [
            "  This report was generated from a LIVE TCP connect scan.",
            f"  The user confirmed authorization to test this target at: {auth_ts}",
            "",
            "  IMPORTANT: Only scan systems you own or have explicit written",
            "  authorization to test. Unauthorized scanning may be illegal.",
            "",
        ]
    else:
        lines += [
            "  This report was generated from predefined educational lab fixture",
            "  data representing simulated service exposures. No live port scanning,",
            "  network exploration, or active vulnerability detection was performed.",
            "",
        ]

    # ── Executive Summary ────────────────────────────────────────────────────
    lines += [
        sep,
        "  EXECUTIVE SUMMARY",
        sep,
        "",
    ]
    words = analysis["executive_summary"].split()
    line  = "  "
    for word in words:
        if len(line) + len(word) + 1 > 72:
            lines.append(line)
            line = "  " + word + " "
        else:
            line += word + " "
    if line.strip():
        lines.append(line)

    # ── Risk Summary ─────────────────────────────────────────────────────────
    lines += [
        "",
        sep,
        f"  RISK SUMMARY ({'LIVE' if live_scan else 'SIMULATED'})",
        sep,
        "",
    ]
    sc = analysis["severity_counts"]
    lines += [
        f"  Critical Findings    : {sc['critical']}",
        f"  High Findings        : {sc['high']}",
        f"  Medium Findings      : {sc['medium']}",
        f"  Low Findings         : {sc['low']}",
        f"  Total Services       : {analysis['services_total']}",
        f"  Open Services        : {analysis['open_services']}",
        "",
    ]

    # ── Findings Table ────────────────────────────────────────────────────────
    lines += [
        sep,
        f"  {'LIVE' if live_scan else 'SIMULATED'} EXPOSURE FINDINGS",
        sep,
        "",
    ]

    for idx, finding in enumerate(analysis["findings"], start=1):
        data_src = finding.get("data_source", "local")
        src_tag  = "[OSV.dev]" if data_src == "osv.dev" else "[Local Rules]"
        lines += [
            f"  [{idx}] {finding['service']}  (Port {finding['port']})  {src_tag}",
            thin_sep,
            f"  Severity          : {finding['severity'].upper()}",
            f"  Reference Check   : {finding['cve']}",
        ]

        if finding.get("banner"):
            lines.append(f"  Detected Banner   : {finding['banner'][:80]}")

        lines.append("  Description       :")
        # Word-wrap description
        desc_words = finding["description"].split()
        line = "    "
        for word in desc_words:
            if len(line) + len(word) + 1 > 72:
                lines.append(line)
                line = "    " + word + " "
            else:
                line += word + " "
        if line.strip():
            lines.append(line)

        lines.append("  Recommendation    :")
        rec_words = finding["recommendation"].split()
        line = "    "
        for word in rec_words:
            if len(line) + len(word) + 1 > 72:
                lines.append(line)
                line = "    " + word + " "
            else:
                line += word + " "
        if line.strip():
            lines.append(line)

        lines += [f"  Security Ref      : {finding['reference']}", ""]

    # ── Footer ────────────────────────────────────────────────────────────────
    lines += [
        sep,
        "  CYBEX RECON ENGINE — Educational Security Assessment Platform",
        "  Only scan systems you own or have explicit written authorization to test.",
        sep,
        "",
    ]

    return "\n".join(lines)


def generate_json_report(analysis: dict) -> str:
    """
    Render *analysis* results as a pretty-printed JSON report.

    Parameters
    ----------
    analysis : dict
        The analysis result generated by services/analysis.py.

    Returns
    -------
    str
        Pretty-printed JSON report string.
    """
    report_id    = analysis.get("report_id") or str(uuid.uuid4())
    generated_at = analysis.get("generated_at") or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    live_scan    = analysis.get("live_scan", False)
    auth_ts      = analysis.get("auth_confirmed_at")

    report = {
        "report_meta": {
            "tool":              "Cybex Recon Engine",
            "module":            "Module 3 — Security Analysis & Reporting",
            "report_id":         report_id,
            "generated_at":      generated_at,
            "scan_type":         "live" if live_scan else "simulated",
            "live_scan":         live_scan,
            "auth_confirmed_at": auth_ts,
            "disclaimer": (
                "LIVE scan: Only scan systems you own or have explicit written authorization to test. "
                if live_scan else
                "Generated from predefined educational lab fixture data. "
                "No live port scanning or active vulnerability detection was performed."
            ),
        },
        "target":           analysis["target"],
        "scenario":         analysis["scenario"],
        "assessment_date":  analysis["assessment_date"],
        "analysis_date":    analysis["analysis_date"],
        "risk_score":       analysis["risk_score"],
        "risk_label":       analysis["risk_label"],
        "score_breakdown":  analysis.get("score_breakdown", {}),
        "executive_summary": analysis["executive_summary"],
        "risk_summary": {
            "total_services":  analysis["services_total"],
            "open_services":   analysis["open_services"],
            "severity_counts": analysis["severity_counts"],
        },
        "findings": analysis["findings"],
    }
    return json.dumps(report, indent=2, ensure_ascii=False)
